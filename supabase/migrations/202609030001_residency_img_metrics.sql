begin;

create table public.residency_img_metrics (
  id bigint generated by default as identity primary key,
  residency_id bigint not null references public.residencies(id) on delete cascade,
  reporting_year smallint not null check (reporting_year between 2000 and 2100),
  period_kind text not null check (period_kind in ('annual', 'three_year_average')),
  metric_type text not null check (
    metric_type in ('img_resident_share', 'img_matched_share', 'img_acceptance_rate')
  ),
  img_percentage numeric(5, 2) not null check (img_percentage between 0 and 100),
  img_count integer check (img_count is null or img_count >= 0),
  total_count integer check (total_count is null or total_count > 0),
  source_name text not null,
  source_url text not null check (source_url ~ '^https?://'),
  source_updated_at date,
  date_checked date not null,
  methodology_note text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (residency_id, reporting_year, period_kind, metric_type, source_url),
  check (
    (img_count is null and total_count is null)
    or (img_count is not null and total_count is not null and img_count <= total_count)
  )
);

create index residency_img_metrics_residency_year_idx
on public.residency_img_metrics(residency_id, reporting_year desc);

create trigger residency_img_metrics_updated
before update on public.residency_img_metrics
for each row execute function public.set_updated_at();

alter table public.residency_img_metrics enable row level security;

create policy residency_img_metrics_authenticated_read
on public.residency_img_metrics
for select to authenticated using (true);

create policy residency_img_metrics_admin_all
on public.residency_img_metrics
for all to authenticated
using (public.current_user_role() = 'admin')
with check (public.current_user_role() = 'admin');

grant select, insert, update, delete on public.residency_img_metrics to authenticated;
grant usage, select on sequence public.residency_img_metrics_id_seq to authenticated;

comment on table public.residency_img_metrics is
  'Sourced program-level IMG measures. Resident composition, match share, and applicant acceptance rate are intentionally distinct metrics.';

comment on column public.residency_img_metrics.img_percentage is
  'Percentage for metric_type; never infer an applicant acceptance probability from resident composition.';

create table public.residency_img_research_status (
  residency_id bigint primary key references public.residencies(id) on delete cascade,
  status text not null check (status in ('available', 'not_reported', 'not_found', 'error')),
  source_url text not null check (source_url ~ '^https?://'),
  date_checked date not null,
  error_detail text,
  updated_at timestamptz not null default now()
);

create trigger residency_img_research_status_updated
before update on public.residency_img_research_status
for each row execute function public.set_updated_at();

alter table public.residency_img_research_status enable row level security;

create policy residency_img_research_status_authenticated_read
on public.residency_img_research_status
for select to authenticated using (true);

create policy residency_img_research_status_admin_all
on public.residency_img_research_status
for all to authenticated
using (public.current_user_role() = 'admin')
with check (public.current_user_role() = 'admin');

grant select, insert, update, delete
on public.residency_img_research_status to authenticated;

commit;
