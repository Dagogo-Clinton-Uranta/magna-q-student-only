  verification_status = excluded.verification_status,
  current_information_warning = excluded.current_information_warning;

do $$
declare
  imported_count integer;
  additional_count integer;
  literal_unknown_count integer;
begin
  select count(*) into imported_count from public.residencies;
  if imported_count <> 171 then
    raise exception 'Expected 171 unique residency rows after the additional imports, found %', imported_count;
  end if;

  select count(*) into additional_count
  from public.residencies
  where source_order between 137 and 171;
  if additional_count <> 35 then
    raise exception 'Expected 35 additional residency rows, found %', additional_count;
  end if;

  select count(*) into literal_unknown_count
  from public.residencies as residency
  cross join lateral jsonb_each_text(to_jsonb(residency)) as entry
  where lower(btrim(entry.value)) in ('unknown', 'unkown');
  if literal_unknown_count <> 0 then
    raise exception 'Expected optional unknown values to be null, found % literals', literal_unknown_count;
  end if;
end;
$$;

