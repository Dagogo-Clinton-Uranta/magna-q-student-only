insert into public.residency_event_programs (
  event_id,
  residency_program_id,
  match_method,
  match_confidence
)
select
  event.id,
  program.id,
  'user_supplied_institution_and_specialty',
  1.000
from event_program_matches as match
join public.residency_events as event
  on event.event_date = match.event_date
 and event.listed_institution_name = match.institution_name
join public.residency_programs as program
  on program.program_name = match.program_name
 and program.specialty = match.specialty
on conflict (event_id, residency_program_id) do update
set
  match_method = excluded.match_method,
  match_confidence = excluded.match_confidence;

insert into public.residency_event_research_status (
  residency_program_id,
  search_status,
  last_checked_at,
  search_notes
)
select distinct
  link.residency_program_id,
  'found_upcoming',
  timestamptz '2026-09-04 00:00:00+00',
  'Upcoming event recorded from the user-supplied event list on 2026-09-04; source not independently verified.'
from public.residency_event_programs as link
join public.residency_events as event on event.id = link.event_id
where event.source_type in ('user_supplied_event_list', 'user_supplied_official_url')
  and event.date_checked = date '2026-09-04'
  and event.status = 'upcoming'
on conflict (residency_program_id) do update
set
  search_status = excluded.search_status,
  last_checked_at = excluded.last_checked_at,
  search_notes = excluded.search_notes;

