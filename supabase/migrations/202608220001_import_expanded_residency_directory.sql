create or replace function public.get_residency_filter_options()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'specialties', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object('label', options.specialty, 'value', options.specialty)
          order by options.specialty
        )
        from (
          select distinct specialty
          from public.residencies
          where specialty is not null
        ) as options
      ),
      '[]'::jsonb
    ),
    'locations', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'label', options.city || ', ' || options.state,
            'value', options.state || '|' || options.city
          )
          order by options.state, options.city
        )
        from (
          select distinct city, state
          from public.residencies
          where city is not null and state is not null
        ) as options
      ),
      '[]'::jsonb
    )
  );
$$;

