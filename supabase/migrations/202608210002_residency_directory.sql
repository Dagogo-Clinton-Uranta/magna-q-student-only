create function public.get_residency_filter_options()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'specialties', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object('label', options.specialty, 'value', options.specialty_filter_key)
          order by options.specialty
        )
        from (
          select distinct specialty, specialty_filter_key
          from public.residencies
        ) as options
      ),
      '[]'::jsonb
    ),
    'locations', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'label', options.city || ', ' || options.state,
            'value', options.location_filter_key
          )
          order by options.state, options.city
        )
        from (
          select distinct city, state, location_filter_key
          from public.residencies
        ) as options
      ),
      '[]'::jsonb
    )
  );
$$;

revoke all on function public.get_residency_filter_options() from public;
